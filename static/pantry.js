const norm = (s) => (s || '').toLowerCase().replace(/ё/g, 'е');
const tokensOf = (s) => norm(s).match(/[a-zа-я]+/g) || [];

function parseRule(rule) {
  const pos = [];
  const neg = [];
  for (const part of rule.split(' ')) {
    if (!part) continue;
    (part[0] === '-' ? neg : pos).push((part[0] === '-' ? part.slice(1) : part).split('|'));
  }
  return { pos, neg };
}
const altHit = (alt, t) => (alt.endsWith('$') ? t === alt.slice(0, -1) : t.startsWith(alt));
const anyHit = (alts, tokens) => alts.some((a) => tokens.some((t) => altHit(a, t)));
const ruleHit = (r, tokens) => r.pos.every((alts) => anyHit(alts, tokens)) && !r.neg.some((alts) => anyHit(alts, tokens));

export const PRODUCTS = P.map(([key, group, rules, also]) => ({ key, group, label: key[0].toUpperCase() + key.slice(1), rules: rules.map(parseRule), also: also || [] }));
const BY_KEY = new Map(PRODUCTS.map((p) => [p.key, p]));

