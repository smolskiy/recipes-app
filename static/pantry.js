// Продукт ингредиента: { key, label, group, optional }. Неизвестные продукты — по своему названию.
const keyCache = new Map();
export function ingredientKey(ing) {
  const name = ing?.name || '';
  const sq = ing?.shop_query || '';
  const ck = name + '|' + sq;
  let hit = keyCache.get(ck);
  if (!hit) {
    const find = (text) => {
      const tokens = tokensOf(text);
      return tokens.length ? PRODUCTS.find((pr) => pr.rules.some((r) => ruleHit(r, tokens))) : null;
    };
    // «Молоко или сливки», «кефир/йогурт» — первый вариант; не узнали его — всё название целиком.
    const first = name.split(/\s+или\s+|\//)[0];
    // Обычно точнее само название. Но голое «Масло» или «Перец» узнаётся как продукт «всегда есть дома»,
    // а запрос для магазина уточняет: «масло сливочное», «перец болгарский».
    let p = find(first) || find(name);
    if (!p || p.group === 'staple') p = find(sq) || p;
    hit = p ? { key: p.key, label: p.label, group: p.group } : null;
    // Заголовок группы, записанный как ингредиент («Для теста:», «Крем»): у настоящих продуктов
    // модель пишет запрос для магазина (его нет только у воды и льда).
    const header = /:\s*$/.test(name) || /^\s*для\s/i.test(name) || !sq.trim();
    if (!hit && !header) {
      const words = norm(name).replace(/\([^)]*\)/g, ' ').split(/[,/;:]| или /)[0].match(/[a-zа-я-]+/g) || [];
      const key = words.filter((w) => w.length > 1 && !FILLER.some((f) => w.startsWith(f))).slice(0, 2).join(' ');
      hit = key ? { key, label: key[0].toUpperCase() + key.slice(1), group: 'other' } : null;
    }
    keyCache.set(ck, hit);
  }
  if (!hit) return null;
  return { ...hit, optional: OPTIONAL.test(norm(ing?.note) + ' ' + norm(name)) };
}

export const productLabel = (key) => BY_KEY.get(key)?.label || (key ? key[0].toUpperCase() + key.slice(1) : '');
export const productGroup = (key) => BY_KEY.get(key)?.group || 'other';

// Продукты рецепта: обязательные (без «по вкусу» и «для подачи»), без повторов.
const needCache = new WeakMap();
export function recipeNeeds(r) {
  let need = needCache.get(r);
  if (!need) {
    need = new Map();
    for (const ing of r.ingredients || []) {
      const k = ingredientKey(ing);
      if (k && !k.optional && !need.has(k.key)) need.set(k.key, k);
    }
    needCache.set(r, need);
  }
  return need;
}

function hasProduct(key, have) {
  if (have.has(key)) return true;
  return (BY_KEY.get(key)?.also || []).some((k) => have.has(k));
}

// Подбор: для каждого рецепта — чего не хватает и сколько отмеченных продуктов он использует.
// Возвращает только рецепты, где не хватает не больше maxMissing и есть хотя бы один отмеченный продукт.
export function matchPantry(items, pantry, { staples = DEFAULT_STAPLES, ignoreSpices = true, maxMissing = 2 } = {}) {
  const have = new Set([...pantry, ...staples]);
  const mine = new Set(pantry);
  const out = [];
  for (const r of items) {
    const need = recipeNeeds(r);
    if (!need.size) continue;
    const missing = [];
    let used = 0;
    for (const [key, k] of need) {
      if (hasProduct(key, mine)) used++;
      if (hasProduct(key, have) || (ignoreSpices && k.group === 'spice')) continue;
      missing.push(k.label);
      if (missing.length > maxMissing) break;
    }
    if (missing.length <= maxMissing && used > 0) out.push({ item: r, missing, used });
  }
  out.sort((a, b) => a.missing.length - b.missing.length || b.used - a.used
    || (b.item.video_views || 0) - (a.item.video_views || 0) || (a.item.title || '').localeCompare(b.item.title || '', 'ru'));
  return out;
}

// Продукты, которые встречаются в рецептах (для выбора): [{ key, label, group, count }], частые — первыми.
export function productCatalog(items) {
  const counts = new Map();
  for (const r of items) {
    for (const [key, k] of recipeNeeds(r)) {
      const c = counts.get(key) || { key, label: k.label, group: k.group, count: 0 };
      c.count++;
      counts.set(key, c);
    }
  }
  return [...counts.values()].sort((a, b) => b.count - a.count || a.label.localeCompare(b.label, 'ru'));
}
